let isInitialized = false;

export async function ensureStateColumn(db) {
  if (isInitialized) return;
  try {
    await db.execute("ALTER TABLE sites ADD COLUMN state TEXT;");
  } catch (e) {
    // Column already exists or table altered
  }
  isInitialized = true;
}
